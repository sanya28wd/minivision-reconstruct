-- ADR 0010 / RPT-14. Tamper-evident, hash-chained audit log.
CREATE TABLE audit_log (
    sequence_number bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id uuid NOT NULL UNIQUE,
    occurred_at timestamptz NOT NULL DEFAULT now(),
    event_type text NOT NULL,
    actor text NOT NULL CHECK (actor IN ('visitor', 'admin', 'anonymous', 'system')),
    session_id uuid,
    link_id uuid,
    request_id uuid,
    run_id uuid,
    action text NOT NULL,
    status_code integer,
    target_type text,
    target_id text,
    details jsonb NOT NULL DEFAULT '{}'::jsonb,
    prev_hash text NOT NULL,
    hash text NOT NULL
);

CREATE INDEX audit_log_occurred_at_idx ON audit_log (occurred_at);
CREATE INDEX audit_log_request_id_idx ON audit_log (request_id);
CREATE INDEX audit_log_run_id_idx ON audit_log (run_id);

CREATE OR REPLACE FUNCTION audit_log_prevent_mutation()
RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'audit_log rows are immutable: % operations are forbidden', TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER audit_log_no_update_delete
BEFORE UPDATE OR DELETE ON audit_log
FOR EACH ROW
EXECUTE FUNCTION audit_log_prevent_mutation();

-- Row-level triggers never fire on TRUNCATE, so a separate statement-level trigger blocks wiping the log.
-- PostgreSQL docs: TRUNCATE triggers are allowed "only FOR EACH STATEMENT"
-- (https://www.postgresql.org/docs/16/sql-createtrigger.html).
CREATE TRIGGER audit_log_no_truncate
BEFORE TRUNCATE ON audit_log
FOR EACH STATEMENT
EXECUTE FUNCTION audit_log_prevent_mutation();

REVOKE UPDATE, DELETE ON audit_log FROM PUBLIC;

DROP TABLE IF EXISTS access_events;
